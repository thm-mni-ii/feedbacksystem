import { BENCHMARK_SCENARIOS, type evaluateSelection } from './selectionBenchmark'

type Report = ReturnType<typeof evaluateSelection>
const strategies = ['random', 'coverage-weighted', 'expected-information-gain'] as const
const scenarioNames = ['Niedrig', 'Gemischt', 'Hoch', 'Abweichend']

export function renderChapterResults(report: Report): string {
  const summaries = report.summaries.filter((summary) => summary.pool === 'platform-testdata')
  const number = (value: number, digits = 4) => value.toFixed(digits).replace('.', '{,}')
  const metricTable = (command: string, metric: string, baseline?: string, percentage = false) => {
    const rows = BENCHMARK_SCENARIOS.flatMap((scenario, scenarioIndex) =>
      Array.from({ length: report.sessionCount }, (_, index) => {
        const cells = strategies.map((strategy) => {
          const summary = summaries.find(
            (item) =>
              item.scenario === scenario.id &&
              item.strategy === strategy &&
              item.sessionNumber === index + 1
          )
          if (!summary) return '--'
          const value = summary.metrics[metric]
          if (!value) throw new Error(`Missing chapter metric: ${metric}`)
          const scale = percentage ? 100 : 1
          const digits = percentage ? 1 : 4
          const reference = baseline ? `\\\\(${number(summary.metrics[baseline].mean)})` : ''
          const sample = summary.runCount === report.seeds.length ? '' : `_{n=${summary.runCount}}`
          return `\\shortstack{$${number(value.mean * scale, digits)} \\pm ${number(value.sampleStandardDeviation * scale, digits)}${sample}$${reference}}`
        })
        return `${scenarioNames[scenarioIndex]} & ${index + 1} & ${cells.join(' & ')} \\\\`
      })
    )
    return `\\newcommand{\\${command}}{%\n\\begin{tabular}{llccc}\n\\hline\nSituation & Sitzung & Zufall & Bewertungen + Lernstand & Informationsgewinn \\\\\n\\hline\n${rows.join('\n')}\n\\hline\n\\end{tabular}}\n`
  }
  const plot = (command: string, metric: string, ylabel: string, percentage = false) => {
    const panels = BENCHMARK_SCENARIOS.map((scenario, scenarioIndex) => {
      const lines = strategies.map((strategy, strategyIndex) => {
        const coords = summaries
          .filter((item) => item.scenario === scenario.id && item.strategy === strategy)
          .map(
            (item) =>
              `(${item.sessionNumber},${item.metrics[metric].mean * (percentage ? 100 : 1)})`
          )
          .join(' ')
        return `\\addplot+[mark=${['*', 'square*', 'triangle*'][strategyIndex]}] coordinates {${coords}};`
      })
      return `\\begin{minipage}{0.48\\textwidth}\\centering
\\begin{tikzpicture}
\\begin{axis}[width=\\linewidth,height=5cm,title={${scenarioNames[scenarioIndex]}},xlabel={Sitzung},ylabel={${ylabel}},xmin=1,xmax=${report.sessionCount},xtick={1,...,${report.sessionCount}},ymin=0,grid=major,tick label style={font=\\scriptsize},label style={font=\\scriptsize}]
${lines.join('\n')}
\\end{axis}
\\end{tikzpicture}
\\end{minipage}${scenarioIndex % 2 === 0 ? '\\hfill' : '\\par\\medskip'}`
    })
    return `\\newcommand{\\${command}}{%\n${panels.join('\n')}\n\\par\\smallskip\\footnotesize Blau/Kreise: Zufall; Rot/Quadrate: Bewertungen und Lernstand; Braun/Dreiecke: Informationsgewinn.}\n`
  }
  const endpointRows = BENCHMARK_SCENARIOS.map((scenario, index) => {
    const cells = strategies.map((strategy) => {
      const endpoints = report.seeds.map((seed) => {
        const trajectory = report.runs.filter(
          (run) =>
            run.pool === 'platform-testdata' &&
            run.scenario === scenario.id &&
            run.strategy === strategy &&
            run.seed === seed
        )
        const last = trajectory.at(-1)
        if (!last) throw new Error(`Missing chapter trajectory: ${scenario.id}/${strategy}/${seed}`)
        return {
          tasks: trajectory.reduce((sum, run) => sum + run.taskCount, 0),
          error: last.finalMasteryBrierScore,
          covered:
            new Set(trajectory.flatMap((run) => run.observations.map((item) => item.competencyId)))
              .size / last.competencyStatesAfter.length
        }
      })
      const average = (key: 'tasks' | 'error' | 'covered') =>
        endpoints.reduce((sum, item) => sum + item[key], 0) / endpoints.length
      return `$${number(average('tasks'), 1)}$ & $${number(average('covered') * 100, 1)}$ & $${number(average('error'))}$`
    })
    return `${scenarioNames[index]} & ${cells.join(' & ')} \\\\`
  })
  const platformRuns = report.runs.filter((run) => run.pool === 'platform-testdata')
  return (
    `% Generated by npm run evaluate; experiment ${report.experiment}.\n` +
    `\\newcommand{\\EvaluationSessions}{${platformRuns.length}}\n` +
    `\\newcommand{\\EvaluationAnswers}{${platformRuns.reduce((sum, run) => sum + run.taskCount, 0)}}\n` +
    `\\newcommand{\\EvaluationEvidenceEnds}{${platformRuns.filter((run) => run.endReason === 'evidence').length}}\n` +
    `\\newcommand{\\EvaluationNoQuestionEnds}{${platformRuns.filter((run) => run.endReason === 'no-question').length}}\n` +
    metricTable('EvaluationBrierTable', 'brierScore', 'initialPredictionBrierScore') +
    metricTable('EvaluationLogLossTable', 'logLoss', 'initialPredictionLogLoss') +
    metricTable('EvaluationNeedTable', 'unmasteredTargetRate', undefined, true) +
    metricTable('EvaluationCoverageTable', 'competencyCoverage', undefined, true) +
    plot('EvaluationBrierPlot', 'brierScore', 'Brier-Wert') +
    plot('EvaluationNeedPlot', 'unmasteredTargetRate', 'Noch nicht beherrscht (\\%)', true) +
    plot('EvaluationCoveragePlot', 'competencyCoverage', 'Abdeckung (\\%)', true) +
    `\\newcommand{\\EvaluationEndpointTable}{%\n\\begin{tabular}{lrrrrrrrrr}\n\\hline\n& \\multicolumn{3}{c}{Zufall} & \\multicolumn{3}{c}{Bewertungen + Lernstand} & \\multicolumn{3}{c}{Informationsgewinn} \\\\\nSituation & Aufgaben & Abdeckung & Brier & Aufgaben & Abdeckung & Brier & Aufgaben & Abdeckung & Brier \\\\\n\\hline\n${endpointRows.join('\n')}\n\\hline\n\\end{tabular}}\n`
  )
}
